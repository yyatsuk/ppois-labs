#pragma once
#include <iostream>
#include <vector>

/**
 * @brief Лента машины Поста: бесконечная последовательность ячеек,
 *        каждая из которых либо пуста, либо содержит метку.
 *
 * Текстовый формат ленты: строка из символов '0' (пусто) и '1' (метка),
 * затем через пробел индекс ячейки, на которой стоит каретка. Пример: "00100 2".
 */
class Tape {
public:
    /// Создаёт ленту из одной пустой ячейки, каретка стоит на ней.
    Tape();

    /// Конструктор копирования.
    Tape(const Tape& other);

    /// Оператор присваивания копированием.
    Tape& operator=(const Tape& other);

    /// Деструктор (память освобождает std::vector).
    ~Tape() = default;

    /// Ставит метку в текущей ячейке.
    void mark();

    /// Убирает метку из текущей ячейки.
    void erase();

    /// Возвращает true, если в текущей ячейке есть метка.
    bool isMarked() const;

    /// Сдвигает каретку вправо (префиксный инкремент). Лента расширяется при необходимости.
    Tape& operator++();

    /// Сдвигает каретку влево (префиксный декремент). Лента расширяется при необходимости.
    Tape& operator--();

    /// Возвращает индекс ячейки, на которой стоит каретка.
    int position() const;

    /// Сравнивает ленты: совпадают ячейки и позиция каретки.
    bool operator==(const Tape& other) const;

    /// Возвращает true, если ленты различаются.
    bool operator!=(const Tape& other) const;

    /// Записывает ленту в поток в формате "ячейки позиция".
    friend std::ostream& operator<<(std::ostream& os, const Tape& tape);

    /**
     * @brief Читает ленту из потока в формате "ячейки позиция".
     *
     * При неверных данных (посторонний символ, позиция вне ленты)
     * поток переходит в состояние failbit, а лента остаётся прежней.
     */
    friend std::istream& operator>>(std::istream& is, Tape& tape);

private:
    /// Ячейки ленты: true означает метку, false означает пустую ячейку.
    std::vector<bool> cells_;

    /// Индекс ячейки, на которой стоит каретка.
    int position_;

    /// Добавляет пустую ячейку справа, если каретка вышла за границу ленты.
    void ensureCellExists();
};